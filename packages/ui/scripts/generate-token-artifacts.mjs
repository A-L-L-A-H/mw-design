#!/usr/bin/env node
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const uiRoot = resolve(fileURLToPath(new URL('..', import.meta.url)));
const distDir = join(uiRoot, 'dist');

const {
  CORE_DESIGN_TOKENS,
  exportDesignTokenBundle,
  exportTailwindThemeExtend,
  exportTokensToCssVariables,
  exportTokensToW3cJson,
} = await import('../dist/token-exporter.js');

mkdirSync(distDir, { recursive: true });

const w3cTokens = exportTokensToW3cJson(CORE_DESIGN_TOKENS);
const fullBundle = exportDesignTokenBundle(CORE_DESIGN_TOKENS);
const cssVars = exportTokensToCssVariables(CORE_DESIGN_TOKENS);
const twExtend = exportTailwindThemeExtend(CORE_DESIGN_TOKENS);

const tailwindPresetCss = [
  '/* Generated by @moonwitness/ui build — Tailwind v4 @theme preset */',
  '@theme {',
  ...Object.entries(twExtend.colors).map(([k, v]) => `  --color-${k}: ${v};`),
  ...Object.entries(twExtend.spacing).map(([k, v]) => `  --spacing-${k}: ${v};`),
  ...Object.entries(twExtend.borderRadius).map(([k, v]) => `  --radius-${k}: ${v};`),
  '}',
  '',
].join('\n');

const artifacts = [
  { file: join(distDir, 'tokens.w3c.json'), content: `${JSON.stringify(w3cTokens, null, 2)}\n` },
  { file: join(distDir, 'tokens.bundle.json'), content: `${JSON.stringify(fullBundle, null, 2)}\n` },
  { file: join(distDir, 'tokens.generated.css'), content: cssVars },
  { file: join(distDir, 'tailwind-preset.css'), content: tailwindPresetCss },
];

for (const artifact of artifacts) {
  mkdirSync(dirname(artifact.file), { recursive: true });
  writeFileSync(artifact.file, artifact.content, 'utf8');
}

console.log(`Generated ${artifacts.length} design token artifacts in packages/ui/dist.`);
